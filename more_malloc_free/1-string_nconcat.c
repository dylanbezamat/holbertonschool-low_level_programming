#include <stdlib.h>
#include "main.h"

/**
 * string_nconcat - concatene deux chaines
 * @s1: premiere chaine
 * @s2: seconde chaine
 * @n: nombre maximum d'octets de s2 a copier
 *
 * Return: pointeur vers la nouvelle chaine, ou NULL en cas d'echec
 */
char *string_nconcat(char *s1, char *s2, unsigned int n)
{
	char *str;
	unsigned int len1 = 0, len2 = 0, i, j;

	if (s1 == NULL)
		s1 = "";
	if (s2 == NULL)
		s2 = "";

	while (s1[len1] != '\0')
		len1++;
	while (s2[len2] != '\0')
		len2++;

	if (n >= len2)
		n = len2;

	str = malloc(len1 + n + 1);
	if (str == NULL)
		return (NULL);

	for (i = 0; i < len1; i++)
		str[i] = s1[i];
	for (j = 0; j < n; j++)
		str[i + j] = s2[j];
	str[i + j] = '\0';

	return (str);
}
